"""Remote workspace and credential persistence ports."""

from typing import Protocol


class HostedWorkspaceGateway(Protocol):
    def identity(self): ...
    def snapshot(self): ...
    def list(self, kind, **filters): ...
    def create(self, kind, *args, **values): ...
    def set_schedule(self, *args, **values): ...
    def pause_schedule(self, job_id): ...


class ProfileRepository(Protocol):
    def read(self): ...
    def write(self, value): ...


class CredentialStore(Protocol):
    def get_password(self, service, name): ...
    def set_password(self, service, name, value): ...
    def delete_password(self, service, name): ...
