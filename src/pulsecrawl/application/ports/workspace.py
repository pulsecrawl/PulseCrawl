"""Workspace ports expose operations, never SQL connections or filesystem paths."""

from __future__ import annotations
from contextlib import AbstractContextManager, AbstractAsyncContextManager
from typing import Any, Mapping, Protocol


class CatalogRepository(Protocol):
    def list(self) -> list[dict[str, Any]]: ...
    def get(self, identifier: str) -> dict[str, Any]: ...
    def save(self, value: dict[str, Any]) -> dict[str, Any]: ...


class DefinitionRepository(Protocol):
    def list(self) -> list[dict[str, Any]]: ...
    def get(self, identifier: str) -> dict[str, Any]: ...
    def add(self, definition: Mapping[str, Any]) -> None: ...


class ExecutionRepository(Protocol):
    def list(self, job_id: str | None = None) -> list[dict[str, Any]]: ...
    def get(self, execution_id: str) -> dict[str, Any]: ...
    def prepare(self, job_id: str, **options) -> dict[str, Any]:
        """Freeze intent, reserve lifetime budget and create execution atomically."""
        ...

    def start(self, execution_id: str, started_at: str) -> None: ...
    def finish(self, execution_id: str, **options) -> None:
        """Settle budget and terminal state atomically; safe to repeat."""
        ...

    def cancellation_requested(self, execution_id: str) -> bool: ...
    def request_cancellation(
        self, execution_id: str, requested_at: str, mode: str
    ) -> None: ...
    def abandoned(self, status: str) -> list[str]: ...


class ExecutionLease(Protocol):
    def claim(
        self, execution_id: str, owner_token: str, lease_seconds: float
    ) -> None: ...
    def heartbeat(
        self, execution_id: str, owner_token: str, lease_seconds: float
    ) -> bool: ...
    def release(self, execution_id: str, owner_token: str) -> None: ...
    def active(self, execution_id: str) -> bool: ...
    def hold(
        self,
        execution_id: str,
        owner_token: str,
        lease_seconds: float,
        heartbeat_seconds: float,
    ) -> AbstractContextManager: ...


class DefinitionSnapshots(Protocol):
    def write(self, kind: str, identifier: str, value: Mapping[str, Any]) -> None: ...
    def read(self, kind: str, identifier: str) -> dict[str, Any]: ...


class ExecutionRuntimeFactory(Protocol):
    def open(
        self,
        execution: Mapping[str, Any],
        started: str,
        *,
        fetcher=None,
        allow_private_networks=False,
        should_stop=None,
    ) -> AbstractAsyncContextManager:
        """Own resources and reconcile admitted-but-unpublished frontier entries."""
        ...


class DraftRepository(Protocol):
    def list(self): ...
    def get(self, draft_id): ...
    def save(self, draft): ...


class ExecutionTasks(Protocol):
    def register(self, execution_id, task): ...
    def unregister(self, execution_id, task): ...
    def cancel(self, execution_id): ...


class ManifestRepository(Protocol):
    def add_file(self, item, *, change_id): ...
    def replace_files(self, remove, replacements, *, change_id):
        """Publish a version without losing files concurrently added after the read."""
        ...


class RecordFileWriter(Protocol):
    def write(self, *, completed_at=None):
        """Return only after the immutable output file is durable."""
        ...
